import { test, expect } from '@playwright/test'

const ready = page => expect(page.locator('.robot-viewer')).toHaveAttribute('data-status', 'ready', { timeout: 45000 })
const playback = page => page.getByRole('region', { name: '动作播放控制' })
const choose = (page, id) => page.getByLabel('试着对瓦力说', { exact: true }).selectOption(id)
const range = (page, name, value) => page.getByRole('slider', { name, exact: true }).fill(String(value))

test('examples map semantics, keep a light indication directed, and suppress negated actions', async ({ page }) => {
  const errors = []; page.on('pageerror', error => errors.push(error.message))
  await page.goto('/#/virtual'); await ready(page)
  await expect(page.getByRole('tab', { name: '表达实验', exact: true })).toHaveAttribute('aria-selected', 'true')
  await expect(page.getByRole('tablist', { name: '工作台功能' }).getByRole('tab')).toHaveCount(5)
  await choose(page, 'point-gentle')
  await expect(page.locator('.expression-mapping')).toContainText('指示类')
  await expect(page.locator('.expression-mapping')).toContainText('朝向右侧 · 轻幅表达')
  await expect(page.getByRole('slider', { name: '表达强度', exact: true })).toHaveValue('0.35')
  await page.getByRole('button', { name: '预览表达', exact: true }).click()
  await expect(playback(page)).toHaveAttribute('data-source', 'expression')
  await expect.poll(() => page.locator('#joint-headYaw').inputValue(), { intervals: [50] }).toBe('24')
  await range(page, '表达强度', .9)
  await expect(playback(page)).toHaveAttribute('data-playback', 'idle')
  await expect(page.locator('.expression-customized')).toContainText('已手动调整')
  await page.getByRole('button', { name: '预览表达', exact: true }).click()
  await expect.poll(() => page.locator('#joint-headYaw').inputValue(), { intervals: [50] }).toBe('24')
  await choose(page, 'point-negated')
  await expect(playback(page)).toHaveAttribute('data-playback', 'idle')
  await expect(page.locator('.expression-mapping')).toHaveAttribute('data-suppressed', 'true')
  await expect(page.getByRole('button', { name: '预览表达', exact: true })).toBeDisabled()
  await expect(page.getByRole('button', { name: '加入编排', exact: true })).toBeDisabled()
  await expect(playback(page).getByRole('button', { name: '播放', exact: true })).toBeDisabled()
  const pose = await page.locator('.joint-control input').evaluateAll(inputs => inputs.map(input => input.value))
  await page.waitForTimeout(250)
  expect(await page.locator('.joint-control input').evaluateAll(inputs => inputs.map(input => input.value))).toEqual(pose)
  await page.getByRole('button', { name: '依次播放 A → B', exact: true }).click()
  await expect(playback(page).getByRole('button', { name: '暂停', exact: true })).toBeEnabled()
  await playback(page).getByRole('button', { name: '暂停', exact: true }).click()
  await expect(playback(page)).toHaveAttribute('data-playback', 'paused')
  await expect(playback(page).getByRole('button', { name: '继续', exact: true })).toBeEnabled()
  for (const id of ['ack-know', 'ack-received']) {
    await choose(page, id); await expect(page.locator('.expression-mapping')).toContainText('应答类')
    await expect(page.getByRole('button', { name: '预览表达', exact: true })).toBeEnabled()
  }
  expect(errors).toEqual([])
})

test('low context acknowledges first, supports playback controls, and captures an editable timeline snapshot', async ({ page }) => {
  await page.goto('/#/virtual'); await ready(page)
  await page.getByRole('combobox', { name: '交流情境', exact: true }).selectOption('low')
  await expect(page.getByRole('slider', { name: '主体等待', exact: true })).toHaveValue('1100')
  await expect(page.getByRole('slider', { name: '动作节奏', exact: true })).toHaveValue('0.65')
  await page.getByRole('button', { name: '预览表达', exact: true }).click()
  await expect.poll(async () => Number(await page.locator('#joint-neckPitch').inputValue()), { intervals: [50] }).toBeLessThan(0)
  await expect(page.locator('#joint-rightArm')).toHaveValue('0')
  await playback(page).getByRole('button', { name: '暂停', exact: true }).click()
  const neck = await page.locator('#joint-neckPitch').inputValue()
  await page.waitForTimeout(200)
  await expect(page.locator('#joint-neckPitch')).toHaveValue(neck)
  await playback(page).getByRole('button', { name: '继续', exact: true }).click()
  await expect.poll(async () => Number(await page.locator('#joint-rightArm').inputValue())).toBeGreaterThan(5)
  await range(page, '头部左右', 15)
  await expect(playback(page)).toHaveAttribute('data-playback', 'idle')
  await expect(page.locator('#joint-headYaw')).toHaveValue('15')
  await page.getByRole('button', { name: '加入编排', exact: true }).click()
  await expect(page.getByRole('tab', { name: '动作编排', exact: true })).toHaveAttribute('aria-selected', 'true')
  await expect(page.locator('.timeline-steps > li')).toHaveCount(8)
  await page.locator('.timeline-step-select').filter({ hasText: '主体等待' }).click()
  await expect(page.getByRole('spinbutton', { name: '过渡时间', exact: true })).toHaveValue('0.1')
  await expect(page.getByRole('spinbutton', { name: '停留时间', exact: true })).toHaveValue('1')
  const snapshot = await page.locator('.timeline-steps').innerText()
  await page.getByRole('tab', { name: '表达实验', exact: true }).click()
  await expect(page.getByRole('combobox', { name: '交流情境', exact: true })).toHaveValue('low')
  await page.getByRole('combobox', { name: '交流情境', exact: true }).selectOption('meeting')
  await page.getByRole('tab', { name: '动作编排', exact: true }).click()
  expect(await page.locator('.timeline-steps').innerText()).toBe(snapshot)
  await page.getByRole('tab', { name: '内置动作', exact: true }).click()
  await page.getByRole('button', { name: '加入编排：点头回应', exact: true }).click()
  await expect(page.locator('.timeline-steps > li')).toHaveCount(9)
  await page.getByRole('button', { name: '全屏工作台', exact: true }).click()
  await expect(page.locator('canvas')).toHaveCount(1)
  await expect(page.locator('.timeline-steps > li')).toHaveCount(9)
  await page.keyboard.press('Escape')
  await expect(page.getByRole('button', { name: '全屏工作台', exact: true })).toBeFocused()
  await page.reload(); await ready(page)
  await page.getByRole('tab', { name: '我的动作', exact: true }).click()
  await expect(page.locator('.motion-draft-card')).toHaveCount(0)
})

