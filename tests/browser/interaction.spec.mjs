import { test, expect } from '@playwright/test'

test('knowledge walkthrough supports task control, citations and a fresh restart', async ({ page }) => {
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/#/completion')
  const demo = page.getByRole('region', { name: '交互流程演示' })
  const status = demo.getByRole('status')
  await expect(status).toContainText('IDLE')
  await demo.getByRole('button', { name: '开始演示', exact: true }).click()
  await expect(status).toContainText('LISTENING')
  await demo.getByRole('button', { name: '下一步', exact: true }).click()
  await expect(status).toContainText('PLANNING')
  await expect(demo.locator('.interaction-behavior')).toContainText('think')
  await demo.getByRole('button', { name: '下一步', exact: true }).click()
  await expect(status).toContainText('EXECUTING')
  await demo.getByRole('button', { name: '暂停演示', exact: true }).click()
  await expect(status).toContainText('PAUSED')
  await expect(demo.getByRole('button', { name: '下一步', exact: true })).toHaveCount(0)
  await demo.getByRole('button', { name: '继续演示', exact: true }).click()
  await expect(status).toContainText('EXECUTING')
  await demo.getByRole('button', { name: '下一步', exact: true }).click()
  await expect(status).toContainText('SUCCEEDED')
  await expect(demo).toContainText('60 种模型、310 个')
  await demo.locator('summary').click()
  await expect(demo.locator('blockquote')).toContainText('小型与精细配合件23种260件')
  await expect(demo.getByRole('button', { name: '取消演示', exact: true })).toHaveCount(0)
  await demo.getByRole('button', { name: '重置流程演示', exact: true }).click()
  await expect(status).toContainText('IDLE')
  await expect(demo.locator('blockquote')).toHaveCount(0)
  await demo.getByRole('button', { name: '开始演示', exact: true }).click()
  await demo.getByRole('button', { name: '取消演示', exact: true }).click()
  await expect(status).toContainText('CANCELED')
  await expect(demo.getByRole('button', { name: '下一步', exact: true })).toHaveCount(0)
  expect(errors).toEqual([])
})

test('voice and vision scenes reset independently and observation waits for confirmation', async ({ page }) => {
  await page.goto('/#/completion')
  const demo = page.getByRole('region', { name: '交互流程演示' })
  const status = demo.getByRole('status')
  await demo.getByRole('button', { name: /语音交流/ }).click()
  await expect(demo.getByRole('button', { name: /语音交流/ })).toHaveAttribute('aria-pressed', 'true')
  await demo.getByRole('button', { name: '开始演示', exact: true }).click()
  for (let index = 0; index < 3; index++) await demo.getByRole('button', { name: '下一步', exact: true }).click()
  await expect(status).toContainText('SUCCEEDED')
  await expect(demo.locator('.interaction-result')).toContainText('INMP441')
  await demo.getByRole('button', { name: /摄像头观察/ }).click()
  await expect(status).toContainText('IDLE')
  await expect(demo.locator('.interaction-result')).toHaveCount(0)
  await demo.getByRole('button', { name: '开始演示', exact: true }).click()
  await demo.getByRole('button', { name: '下一步', exact: true }).click()
  await demo.getByRole('button', { name: '下一步', exact: true }).click()
  await expect(status).toContainText('WAITING_USER')
  await expect(demo.getByRole('button', { name: '下一步', exact: true })).toHaveCount(0)
  await expect(demo.locator('.interaction-behavior')).toContainText('ask_user')
  await demo.getByRole('button', { name: '确认本次观察', exact: true }).click()
  await expect(status).toContainText('EXECUTING')
  await demo.getByRole('button', { name: '下一步', exact: true }).click()
  await expect(status).toContainText('SUCCEEDED')
  await expect(demo.locator('.interaction-result')).toContainText('文字或语音回应')
  await page.getByRole('navigation', { name: '章节导航' }).getByRole('link', { name: /电路与搭建/ }).click()
  await page.getByRole('navigation', { name: '章节导航' }).getByRole('link', { name: /实体成果/ }).click()
  await expect(status).toContainText('IDLE')
  await expect(demo.getByRole('button', { name: /资料问答/ })).toHaveAttribute('aria-pressed', 'true')
})

test('walkthrough works offline, by keyboard, and at narrow viewport widths', async ({ page }) => {
  const external = []
  await page.route('**/*', route => {
    if (route.request().url().startsWith('http://127.0.0.1:4173/')) return route.continue()
    external.push(route.request().url()); return route.abort()
  })
  await page.goto('/#/completion')
  const demo = page.getByRole('region', { name: '交互流程演示' })
  for (const width of [320, 390, 768, 1440]) {
    await page.setViewportSize({ width, height: 960 })
    for (const scene of ['资料问答', '语音交流', '摄像头观察']) {
      await demo.getByRole('button', { name: new RegExp(scene) }).click()
      expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    }
  }
  await demo.getByRole('button', { name: /资料问答/ }).focus()
  await page.keyboard.press('Enter')
  await demo.getByRole('button', { name: '开始演示', exact: true }).focus()
  await page.keyboard.press('Enter')
  await expect(demo.getByRole('status')).toContainText('LISTENING')
  await expect(page.getByRole('link', { name: '打开交互调试台' })).toHaveAttribute('href', 'http://127.0.0.1:8000')
  expect(external).toEqual([])
})
