test('invalid limits and unavailable browser storage are handled without runtime errors', async ({ page }) => {
  const errors = []; page.on('pageerror', error => errors.push(error.message))
  await page.addInitScript(() => { localStorage.setItem('walle.viewer-settings.v1', '{broken') })
  await page.goto('/#/virtual'); await ready(page)
  await page.getByRole('tab', { name: '校准与状态', exact: true }).click()
  await page.getByRole('spinbutton', { name: '头部左右最大角度' }).fill('999')
  await expect(page.getByRole('alert')).toContainText('头部左右')
  await expect(page.getByRole('button', { name: '应用校准', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: '恢复默认校准', exact: true }).click()
  await page.evaluate(() => { Storage.prototype.setItem = () => { throw new Error('storage unavailable') } })
  await page.getByRole('button', { name: '保存校准与外观配置', exact: true }).click()
  await expect(page.locator('.settings-save-notice')).toContainText('无法保存')
  await page.getByRole('button', { name: '清除部件高亮' }).click()
  await expect(page.locator('.robot-viewer')).toHaveAttribute('data-highlight', '')
  expect(errors).toEqual([])
})

