import { test, expect } from '@playwright/test'
import { createHash } from 'node:crypto'

const ready = page => expect(page.locator('.robot-viewer')).toHaveAttribute('data-status', 'ready', { timeout: 45000 })
const telemetry = page => page.locator('.drive-telemetry')
const coordinate = async (page, name) => Number(await telemetry(page).getAttribute(`data-${name}`))
const hash = buffer => createHash('sha256').update(buffer).digest('hex')
async function setupDrive(page) {
  await page.goto('/#/virtual'); await ready(page)
  await page.getByRole('button', { name: '全屏工作台', exact: true }).click()
  await page.getByRole('tab', { name: '履带驾驶', exact: true }).click()
}

test('keyboard driving moves, turns and stops on release or blur', async ({ page }) => {
  const errors = []; page.on('pageerror', error => errors.push(error.message))
  await setupDrive(page)
  await page.getByRole('checkbox', { name: '键盘驾驶', exact: true }).check()
  await page.keyboard.down('w')
  await expect.poll(() => coordinate(page, 'z')).toBeGreaterThan(.025)
  await page.keyboard.up('w')
  await expect(telemetry(page)).toContainText('0.00 / 0.00')
  const stopped = await coordinate(page, 'z'); await page.waitForTimeout(250)
  expect(await coordinate(page, 'z')).toBe(stopped)
  await page.keyboard.down('a')
  await expect.poll(() => coordinate(page, 'heading')).toBeLessThan(-.15)
  await page.keyboard.up('a')
  await page.keyboard.down('w'); await page.waitForTimeout(250)
  await page.evaluate(() => window.dispatchEvent(new FocusEvent('blur')))
  await expect(telemetry(page)).toContainText('0.00 / 0.00')
  const frozenX = await coordinate(page, 'x'); await page.waitForTimeout(250)
  expect(await coordinate(page, 'x')).toBe(frozenX)
  await page.keyboard.up('w')
  await page.screenshot({ path: 'artifacts/drive-workspace.png' })
  expect(errors).toEqual([])
})

test('independent tracks curve, standard views change the camera, and reset returns to origin', async ({ page }) => {
  await setupDrive(page)
  await page.getByRole('checkbox', { name: '跟随镜头', exact: true }).uncheck()
  await page.getByRole('slider', { name: '左履带速度', exact: true }).fill('50')
  await page.getByRole('slider', { name: '右履带速度', exact: true }).fill('100')
  await expect.poll(() => coordinate(page, 'heading')).toBeLessThan(-.1)
  await page.getByRole('button', { name: '停止行驶', exact: true }).click()
  await expect(telemetry(page)).toContainText('0.00 / 0.00')
  await page.getByRole('button', { name: '位置复位', exact: true }).click()
  await expect.poll(() => coordinate(page, 'x')).toBe(0); await expect.poll(() => coordinate(page, 'z')).toBe(0)
  const images = []
  for (const view of ['front', 'side', 'back', 'top']) {
    await page.getByRole('combobox', { name: '标准视角', exact: true }).selectOption(view)
    await page.waitForTimeout(100)
    images.push(hash(await page.locator('canvas').screenshot()))
  }
  expect(new Set(images).size).toBe(4)
  await page.getByRole('button', { name: '视角复位', exact: true }).click()
  await expect(page.getByRole('combobox', { name: '标准视角', exact: true })).toHaveValue('quarter')
})

