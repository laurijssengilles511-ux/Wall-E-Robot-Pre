import { test, expect } from '@playwright/test'

const ready = page => expect(page.locator('.robot-viewer')).toHaveAttribute('data-status', 'ready', { timeout: 45000 })
async function range(page, name, value) { await page.getByRole('slider', { name, exact: true }).fill(String(value)) }
async function seconds(page, name, value) { const input = page.getByRole('spinbutton', { name, exact: true }); await input.fill(String(value)); await input.press('Tab') }

test('workspace expands without recreating the viewer, preserves the draft, and exits with Escape', async ({ page }) => {
  const modelRequests = [], errors = []
  page.on('request', request => { if (request.url().endsWith('.glb')) modelRequests.push(request.url()) })
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/#/virtual'); await ready(page)
  await range(page, '头部左右', 20)
  await page.getByRole('tab', { name: '动作编排', exact: true }).click()
  await page.getByRole('button', { name: '添加当前姿态' }).click()
  await page.getByRole('button', { name: '全屏工作台', exact: true }).click()
  await expect(page.locator('body')).toHaveClass(/workbench-mode/)
  await expect(page.locator('.site-header')).not.toBeVisible()
  await expect(page.getByRole('slider', { name: '头部左右', exact: true })).toHaveValue('20')
  await expect(page.locator('.timeline-steps > li')).toHaveCount(1)
  await expect(page.locator('canvas')).toHaveCount(1)
  await expect(page.getByRole('slider', { name: '整机转向', exact: true })).toBeInViewport()
  expect(modelRequests).toHaveLength(1)
  await page.keyboard.press('Escape')
  await expect(page.locator('body')).not.toHaveClass(/workbench-mode/)
  await expect(page.locator('.site-header')).toBeVisible()
  await expect(page.getByRole('button', { name: '全屏工作台', exact: true })).toBeFocused()
  await expect(page.locator('.timeline-steps > li')).toHaveCount(1)
  await page.getByRole('tab', { name: '我的动作', exact: true }).click()
  await expect(page.locator('.motion-draft-card')).toContainText('1 个步骤')
  await page.getByRole('button', { name: '继续编辑', exact: true }).click()
  await expect(page.locator('.timeline-steps > li')).toHaveCount(1)
  await page.getByRole('tab', { name: '校准与状态', exact: true }).click()
  await expect(page.getByRole('table')).toContainText('头部左右')
  await expect(page.getByRole('table')).toContainText('20°')
  expect(errors).toEqual([])
})

test('pose frames can be edited, scrubbed, copied, reordered, updated, deleted and played', async ({ page }) => {
  await page.goto('/#/virtual'); await ready(page)
  await page.getByRole('button', { name: '全屏工作台', exact: true }).click()
  await page.getByRole('tab', { name: '动作编排', exact: true }).click()
  await expect(page.getByRole('button', { name: '从头播放' })).toBeDisabled()
  await range(page, '头部左右', 20)
  await page.getByRole('button', { name: '添加当前姿态' }).click()
  await page.getByRole('textbox', { name: '步骤名称' }).fill('看向右侧')
  await seconds(page, '过渡时间', 1); await seconds(page, '停留时间', .5)
  await range(page, '头部左右', -20)
  await page.getByRole('button', { name: '添加当前姿态' }).click()
  await page.getByRole('textbox', { name: '步骤名称' }).fill('看向左侧')
  await seconds(page, '过渡时间', .5); await seconds(page, '停留时间', 0)
  await expect(page.locator('.timeline-steps > li')).toHaveCount(2)
  await range(page, '时间轴播放位置', 500)
  await expect(page.locator('#joint-headYaw')).toHaveValue('10')
  await range(page, '时间轴播放位置', 1300)
  await expect(page.locator('#joint-headYaw')).toHaveValue('20')
  await range(page, '时间轴播放位置', 1750)
  await expect(page.locator('#joint-headYaw')).toHaveValue('0')
  await page.getByRole('button', { name: '复制步骤 2', exact: true }).click()
  await expect(page.locator('.timeline-steps > li')).toHaveCount(3)
  await page.getByRole('button', { name: '上移步骤 3', exact: true }).click()
  await expect(page.locator('.timeline-steps > li').nth(1)).toContainText('副本')
  await page.getByRole('button', { name: '删除步骤 2', exact: true }).click()
  await expect(page.locator('.timeline-steps > li')).toHaveCount(2)
  await range(page, '头部左右', -15)
  await page.getByRole('textbox', { name: '步骤名称' }).fill('更新后的左侧')
  await expect(page.locator('#joint-headYaw')).toHaveValue('-15')
  await page.getByRole('button', { name: '更新为当前姿态' }).click()
  await page.getByRole('button', { name: '从头播放', exact: true }).click()
  const playback = page.getByRole('region', { name: '动作播放控制' })
  await expect(playback).toHaveAttribute('data-playback', 'playing')
  await page.getByRole('button', { name: '暂停', exact: true }).click()
  const paused = await page.locator('#joint-headYaw').inputValue()
  await page.waitForTimeout(200); await expect(page.locator('#joint-headYaw')).toHaveValue(paused)
  await page.getByRole('button', { name: '继续', exact: true }).click()
  await expect(playback).toHaveAttribute('data-playback', 'idle', { timeout: 8000 })
  await expect(playback.getByRole('status')).toContainText('播放完成')
  await expect(page.locator('#joint-headYaw')).toHaveValue('-15')
  await page.getByRole('button', { name: '清空编排', exact: true }).click()
  await expect(page.locator('.timeline-steps > li')).toHaveCount(0)
  await expect(page.getByRole('button', { name: '从头播放' })).toBeDisabled()
})

test('preset steps capture parameters and can be mixed with poses and dragged into order', async ({ page }) => {
  await page.goto('/#/virtual'); await ready(page)
  await range(page, '播放速度', 2)
  await page.getByRole('combobox', { name: '动作方向' }).selectOption('left')
  await page.getByRole('button', { name: '加入编排：挥手招呼' }).click()
  await expect(page.getByRole('tab', { name: '动作编排', exact: true })).toHaveAttribute('aria-selected', 'true')
  await expect(page.getByRole('combobox', { name: '步骤动作速度' })).toHaveValue('2')
  await expect(page.getByRole('combobox', { name: '步骤动作方向' })).toHaveValue('left')
  await page.getByRole('combobox', { name: '插入内置动作' }).selectOption('nod')
  await page.getByRole('button', { name: '添加动作', exact: true }).click()
  await page.getByRole('button', { name: '添加当前姿态' }).click()
  const rows = page.locator('.timeline-steps > li')
  await rows.nth(2).locator('.timeline-drag').dragTo(rows.nth(0))
  await expect(rows.first()).toContainText('姿态')
  await expect(rows).toHaveCount(3)
  await page.getByRole('button', { name: '从头播放', exact: true }).click()
  const playback = page.getByRole('region', { name: '动作播放控制' })
  await expect(playback).toHaveAttribute('data-source', 'timeline')
  await expect.poll(async () => Number(await page.locator('#joint-leftArm').inputValue())).toBeGreaterThan(0)
  await range(page, '时间轴播放位置', 0)
  await expect(playback).toHaveAttribute('data-playback', 'idle')
  await expect(page.locator('#joint-leftArm')).toHaveValue('0')
  await page.getByRole('button', { name: '全屏工作台', exact: true }).click()
  await page.screenshot({ path: 'artifacts/timeline-workspace.png' })
})

