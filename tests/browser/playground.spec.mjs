import { test, expect } from '@playwright/test'
import { createHash } from 'node:crypto'

const ready = page => expect(page.locator('.robot-viewer')).toHaveAttribute('data-status', 'ready', { timeout: 45000 })
const digest = buffer => createHash('sha256').update(buffer).digest('hex')
async function setRange(page, name, value) {
  await page.getByRole('slider', { name, exact: true }).fill(String(value))
}

test('joint sliders change the rendered model, mirror, randomize and reset', async ({ page }) => {
  const errors = []; page.on('pageerror', error => errors.push(error.message))
  await page.setViewportSize({ width: 1440, height: 1600 })
  await page.goto('/#/virtual'); await ready(page)
  await expect(page.getByRole('slider')).toHaveCount(11)
  const canvas = page.locator('canvas'); await canvas.scrollIntoViewIfNeeded()
  const initial = digest(await canvas.screenshot())
  await setRange(page, '左臂抬落', -40)
  await setRange(page, '右夹爪开合', 18)
  await setRange(page, '前舱门', 55)
  await setRange(page, '头部左右', 25)
  await setRange(page, '颈部俯仰', 10)
  await expect(page.locator('#joint-leftArm')).toHaveValue('-40')
  expect(digest(await canvas.screenshot())).not.toBe(initial)
  await canvas.screenshot({ path: 'artifacts/playground-manual-pose.png' })
  await page.getByRole('button', { name: '镜像姿态', exact: true }).click()
  await expect(page.locator('#joint-rightArm')).toHaveValue('-40')
  await expect(page.locator('#joint-leftClaw')).toHaveValue('18')
  await page.getByRole('button', { name: '姿态复位', exact: true }).click()
  for (const input of await page.locator('.joint-control input').all()) await expect(input).toHaveValue('0')
  await page.getByRole('button', { name: '随机姿态', exact: true }).click()
  expect(await page.locator('.joint-control input').evaluateAll(inputs => inputs.some(input => Number(input.value) !== 0))).toBe(true)
  await page.getByRole('button', { name: '姿态复位', exact: true }).click()
  await page.setViewportSize({ width: 1440, height: 1600 })
  await page.evaluate(() => { document.activeElement?.blur(); window.scrollTo(0, 0) })
  await page.waitForTimeout(200)
  await page.locator('.robot-playground').screenshot({ path: 'artifacts/playground-workbench.png' })
  await page.screenshot({ path: 'artifacts/playground-desktop.png', fullPage: true })
  expect(errors).toEqual([])
})

test('presets honor parameters and support pause, resume, stop, manual takeover and completion', async ({ page }) => {
  await page.goto('/#/virtual'); await ready(page)
  await setRange(page, '重复次数', 2); await setRange(page, '播放速度', 2); await setRange(page, '动作幅度', 1)
  await page.getByRole('combobox', { name: '动作方向' }).selectOption('left')
  const panel = page.getByRole('region', { name: '动作播放控制' })
  await page.getByRole('button', { name: '预览动作：挥手招呼' }).click()
  await expect(panel).toHaveAttribute('data-playback', 'playing')
  await expect.poll(async () => Number(await page.locator('#joint-leftArm').inputValue())).toBeGreaterThan(0)
  await page.getByRole('button', { name: '暂停', exact: true }).click()
  await expect(panel).toHaveAttribute('data-playback', 'paused')
  const paused = await page.locator('#joint-leftArm').inputValue()
  await page.waitForTimeout(300)
  await expect(page.locator('#joint-leftArm')).toHaveValue(paused)
  await page.getByRole('button', { name: '继续', exact: true }).click()
  await expect(panel).toHaveAttribute('data-playback', 'playing')
  await setRange(page, '头部左右', 20)
  await expect(panel).toHaveAttribute('data-playback', 'idle')
  await expect(page.locator('#joint-headYaw')).toHaveValue('20')
  await page.getByRole('button', { name: '预览动作：转身观察' }).click()
  await expect(panel).toHaveAttribute('data-playback', 'playing')
  await page.getByRole('button', { name: '停止', exact: true }).click()
  await expect(panel).toHaveAttribute('data-playback', 'idle')
  await page.getByRole('button', { name: '停止并复位', exact: true }).click()
  await setRange(page, '重复次数', 1)
  await page.getByRole('button', { name: '预览动作：点头回应' }).click()
  await expect(panel).toHaveAttribute('data-playback', 'idle', { timeout: 10000 })
  await expect(panel.getByRole('status')).toContainText('播放完成')
  for (const input of await page.locator('.joint-control input').all()) await expect(input).toHaveValue('0')
})

test('unavailable 3D disables motion controls and navigation cancels playback', async ({ page }) => {
  const errors = []; page.on('pageerror', error => errors.push(error.message))
  await page.goto('/#/virtual'); await ready(page)
  await page.getByRole('button', { name: '预览动作：环顾四周' }).click()
  await page.getByRole('navigation').getByRole('link', { name: /结构与制造/ }).click()
  await expect(page.locator('canvas')).toHaveCount(0)
  await page.getByRole('navigation').getByRole('link', { name: /虚拟平台/ }).click(); await ready(page)
  await expect(page.getByRole('region', { name: '动作播放控制' })).toHaveAttribute('data-playback', 'idle')
  await page.locator('canvas').evaluate(canvas => canvas.dispatchEvent(new Event('webglcontextlost', { cancelable: true })))
  await expect(page.getByRole('button', { name: '预览动作：环顾四周' })).toBeDisabled()
  await expect(page.getByRole('slider', { name: '头部左右', exact: true })).toBeDisabled()
  expect(errors).toEqual([])
})

